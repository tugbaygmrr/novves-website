const ICONS = ["flag", "chart", "certificate", "star", "people", "star", "certificate"];
const YEARS = ["2019", "2020", "2021", "2022", "2023", "2024", "2025"];

function buildSection(loc) {
  const t = T[loc];
  const milestones = t.milestones.map((m, i) => {
    const obj = {
      year: YEARS[i],
      title: m.title,
      body: m.body,
      image: IMAGES[`m${i}`],
      icon: ICONS[i],
    };
    if (i === 6) obj.logos = LOGOS_2025;
    return obj;
  });
  return {
    timelineIntro: t.timelineIntro,
    timelineHeadlinePart1: t.timelineHeadlinePart1,
    timelineHeadlineEm1: t.timelineHeadlineEm1,
    timelineHeadlinePart2: t.timelineHeadlinePart2,
    timelineHeadlineEm2: t.timelineHeadlineEm2,
    timelineHeadlinePart3: t.timelineHeadlinePart3,
    milestones,
    goalsTitle: t.goalsTitle,
    goalsIntro: t.goalsIntro,
    goalsPillars: t.goalsPillars,
    goalsAsideImage: IMAGES.goalsAside,
    goalsAsideImageAlt: t.goalsAsideImageAlt,
    bannerTitle: t.bannerTitle,
    bannerLine1: t.bannerLine1,
    bannerLine2: t.bannerLine2,
    bannerLogoAlt: t.bannerLogoAlt,
  };
}

for (const loc of Object.keys(T)) {
  const file = path.join(DICT_DIR, loc, "home.json");
  const raw = fs.readFileSync(file, "utf8");
  const data = JSON.parse(raw);
  data.companyProfileSection = buildSection(loc);
  fs.writeFileSync(file, JSON.stringify(data, null, 2) + "\n", "utf8");
  console.log(`✓ ${loc}: companyProfileSection injected`);
}

